// ─── Date & String Helpers ──────────────────────────────────────────────────

/**
 * Calculates calendar-based age (year difference minus 1 if the birthday has not yet occurred this year).
 * Avoids the ±1 day drift of 365.25 day division around birthdays.
 */
export function calculateAge(dob: Date, referenceDate: Date = new Date()): number {
  const birth = new Date(dob);
  const ref = new Date(referenceDate);
  let age = ref.getFullYear() - birth.getFullYear();
  const m = ref.getMonth() - birth.getMonth();
  if (m < 0 || (m === 0 && ref.getDate() < birth.getDate())) {
    age--;
  }
  return age;
}

export function calculateDaysPending(
  submittedAt: Date,
  referenceDate: Date = new Date()
): number {
  const diffMs = new Date(referenceDate).getTime() - new Date(submittedAt).getTime();
  return Math.floor(diffMs / 86_400_000);
}

/**
 * Checks if two dates fall on the same calendar day (checking both local and UTC representations).
 */
export function isSameCalendarDay(d1: Date, d2: Date): boolean {
  const a = new Date(d1);
  const b = new Date(d2);
  const matchLocal =
    a.getFullYear() === b.getFullYear() &&
    a.getMonth() === b.getMonth() &&
    a.getDate() === b.getDate();
  const matchUtc =
    a.getUTCFullYear() === b.getUTCFullYear() &&
    a.getUTCMonth() === b.getUTCMonth() &&
    a.getUTCDate() === b.getUTCDate();
  return matchLocal || matchUtc;
}

/**
 * Normalizes text: trims leading/trailing whitespace and collapses internal multiple spaces.
 * Note: Paired with Levenshtein edit-distance matching for resilient name comparison.
 */
export function normalizeWhitespace(text: string): string {
  return text.trim().replace(/\s+/g, " ");
}

// Backwards-compatible alias for existing imports
export const normalizeDevanagari = normalizeWhitespace;

/**
 * Checks if two applications have the same normalized applicant name, village, and calendar birth date.
 */
export function isDuplicateApplication(
  app: Pick<Application, "applicantName" | "village" | "dob">,
  other: Pick<Application, "applicantName" | "village" | "dob">
): boolean {
  return (
    normalizeWhitespace(app.applicantName) === normalizeWhitespace(other.applicantName) &&
    normalizeWhitespace(app.village) === normalizeWhitespace(other.village) &&
    isSameCalendarDay(app.dob, other.dob)
  );
}

/**
 * Computes Levenshtein edit distance between two strings
 */
export function computeLevenshtein(a: string, b: string): number {
  const matrix: number[][] = [];
  for (let i = 0; i <= b.length; i++) matrix[i] = [i];
  for (let j = 0; j <= a.length; j++) matrix[0][j] = j;

  for (let i = 1; i <= b.length; i++) {
    for (let j = 1; j <= a.length; j++) {
      if (b.charAt(i - 1) === a.charAt(j - 1)) {
        matrix[i][j] = matrix[i - 1][j - 1];
      } else {
        matrix[i][j] = Math.min(
          matrix[i - 1][j - 1] + 1, // substitution
          matrix[i][j - 1] + 1,     // insertion
          matrix[i - 1][j] + 1      // deletion
        );
      }
    }
  }
  return matrix[b.length][a.length];
}

// ─── Deterministic Rule Engine ──────────────────────────────────────────────

export interface RuleEngineOptions {
  checkDbDuplicates?: boolean;
  existingApplications?: Application[]; // For in-memory / unit testing without hitting database
  now?: Date; // Optional reference date for deterministic testing
  lang?: "hi" | "en"; // Default "hi"
}

/**
 * Deterministic rule-based analysis engine.
 * Supports bilingual outputs (Hindi & English).
 * Always executed first; provides guaranteed, reliable baseline verification.
 */
export async function analyzeWithRules(
  app: Application,
  options: RuleEngineOptions = { checkDbDuplicates: true }
): Promise<AIAnalysisResult> {
  const lang = options.lang || "hi";
  const now = options.now || new Date();
  const age = calculateAge(app.dob, now);
  const daysPending = calculateDaysPending(app.submittedAt, now);
  const missingDocs: string[] = [];
  const inconsistencies: InconsistencyItem[] = [];
  const reasons: string[] = [];
  // Issues already explained by a dedicated reason (avoids stating the same fact twice)
  const coveredIssues = new Set<string>();

  // 1. Missing documents check against the 6 required documents
  const submittedSet = new Set(
    (app.documentsSubmitted || []).map((d) => d.trim().toLowerCase())
  );

  for (const reqDoc of REQUIRED_DOCUMENTS) {
    const isPresent = Array.from(submittedSet).some((submitted) =>
      submitted.includes(reqDoc.toLowerCase())
    );
    if (!isPresent) {
      missingDocs.push(lang === "en" ? DOC_NAME_EN[reqDoc] || reqDoc : reqDoc);
      inconsistencies.push({
        fieldOrDoc: lang === "en" ? DOC_NAME_EN[reqDoc] || reqDoc : reqDoc,
        issue:
          lang === "en"
            ? `Mandatory document '${DOC_NAME_EN[reqDoc] || reqDoc}' is not attached to the application.`
            : `अनिवार्य दस्तावेज़ '${reqDoc}' आवेदन में संलग्न नहीं है।`,
        severity: "CRITICAL",
      });
    }
  }

  // 2. Age eligibility check (must be >= 60)
  const isUnderage = age < MIN_AGE_YEARS;
  if (isUnderage) {
    inconsistencies.push({
      fieldOrDoc: lang === "en" ? "Date of Birth / Age Proof" : "जन्म तिथि / आयु प्रमाण पत्र",
      issue:
        lang === "en"
          ? `Applicant's age is ${age} years, which is below the minimum statutory threshold (${MIN_AGE_YEARS} years).`
          : `आवेदक की आयु ${age} वर्ष है, जो न्यूनतम पात्रता सीमा (${MIN_AGE_YEARS} वर्ष) से कम है।`,
      severity: "CRITICAL",
    });
    reasons.push(
      lang === "en"
        ? `Applicant is ${age} years of age, which does not satisfy the mandatory minimum age of ${MIN_AGE_YEARS} years for Old Age Pension.`
        : `आवेदक की आयु ${age} वर्ष है, जो वृद्धा पेंशन की अनिवार्य न्यूनतम आयु ${MIN_AGE_YEARS} वर्ष की शर्त पूरी नहीं करती।`
    );
    coveredIssues.add(inconsistencies[inconsistencies.length - 1].issue);
  }

  // 3. Income eligibility check (must be <= ₹2,00,000)
  const isOverIncome = app.annualIncome > MAX_ANNUAL_INCOME_INR;
  if (isOverIncome) {
    inconsistencies.push({
      fieldOrDoc: lang === "en" ? "Income Certificate" : "आय प्रमाण पत्र",
      issue:
        lang === "en"
          ? `Recorded annual income of ₹${app.annualIncome.toLocaleString("en-IN")} exceeds the statutory ceiling of ₹${MAX_ANNUAL_INCOME_INR.toLocaleString("en-IN")}.`
          : `दर्ज वार्षिक आय ₹${app.annualIncome.toLocaleString("hi-IN")} है, जो निर्धारित सीमा ₹${MAX_ANNUAL_INCOME_INR.toLocaleString("hi-IN")} से अधिक है।`,
      severity: "CRITICAL",
    });
    reasons.push(
      lang === "en"
        ? `Annual income of ₹${app.annualIncome.toLocaleString("en-IN")} exceeds the maximum permissible limit of ₹${MAX_ANNUAL_INCOME_INR.toLocaleString("en-IN")}.`
        : `वार्षिक आय ₹${app.annualIncome.toLocaleString("hi-IN")} अधिकतम अनुमेय सीमा ₹${MAX_ANNUAL_INCOME_INR.toLocaleString("hi-IN")} से अधिक है।`
    );
    coveredIssues.add(inconsistencies[inconsistencies.length - 1].issue);
  }

  // 4. Bank account holder name comparison (with whitespace normalization & edit distance)
  const normAppName = normalizeWhitespace(app.applicantName);
  const normBankHolder = normalizeWhitespace(app.bankAccountHolder);

  if (normAppName !== normBankHolder) {
    const distance = computeLevenshtein(normAppName, normBankHolder);
    const maxLen = Math.max(normAppName.length, normBankHolder.length);
    const similarity = 1 - distance / maxLen;

    if (similarity >= 0.75 && distance <= 3) {
      // Minor spelling difference -> WARNING
      inconsistencies.push({
        fieldOrDoc: lang === "en" ? "Bank Passbook / Account Holder Name" : "बैंक पासबुक / खाता धारक नाम",
        issue:
          lang === "en"
            ? `Minor spelling variation between bank account holder ('${app.bankAccountHolder}') and applicant name ('${app.applicantName}').`
            : `बैंक खातेदार नाम ('${app.bankAccountHolder}') एवं आवेदक नाम ('${app.applicantName}') में मामूली वर्तनी (spelling) अंतर है।`,
        severity: "WARNING",
      });
      reasons.push(
        lang === "en"
          ? `Minor spelling variation between bank account holder (${app.bankAccountHolder}) and applicant name.`
          : `बैंक खातेदार नाम (${app.bankAccountHolder}) एवं आवेदक नाम में मामूली वर्तनी अंतर है।`
      );
      coveredIssues.add(inconsistencies[inconsistencies.length - 1].issue);
    } else {
      // Major mismatch -> CRITICAL
      inconsistencies.push({
        fieldOrDoc: lang === "en" ? "Bank Passbook / Account Holder Name" : "बैंक पासबुक / खाता धारक नाम",
        issue:
          lang === "en"
            ? `Bank account holder name ('${app.bankAccountHolder}') is completely different from applicant name ('${app.applicantName}').`
            : `बैंक खातेदार का नाम ('${app.bankAccountHolder}') आवेदन में दर्ज नाम ('${app.applicantName}') से पूर्णतः भिन्न है।`,
        severity: "CRITICAL",
      });
      reasons.push(
        lang === "en"
          ? `Bank account is held under a different name (${app.bankAccountHolder}) rather than the applicant (${app.applicantName}). DBT transfer will fail.`
          : `बैंक खाता आवेदक (${app.applicantName}) के नाम पर न होकर अन्य व्यक्ति (${app.bankAccountHolder}) के नाम पर है। DBT अंतरण विफल हो जाएगा।`
      );
      coveredIssues.add(inconsistencies[inconsistencies.length - 1].issue);
    }
  }

  // 5. Expired documents check => CRITICAL severity and forces RETURN
  for (const doc of app.documentsSubmitted || []) {
    if (
      doc.includes("समाप्त") ||
      doc.toLowerCase().includes("expired") ||
      doc.includes("पुराना")
    ) {
      inconsistencies.push({
        fieldOrDoc: doc,
        issue:
          lang === "en"
            ? `Document validity has expired (${doc}). A valid current certificate must be attached.`
            : `दस्तावेज़ की वैधता समाप्त हो चुकी है (${doc})। नवीनतम वैध प्रमाण पत्र संलग्न किया जाना आवश्यक है।`,
        severity: "CRITICAL",
      });
      reasons.push(
        lang === "en"
          ? `Submitted document (${doc}) has expired.`
          : `संलग्न दस्तावेज़ (${doc}) की वैधता समाप्त हो चुकी है।`
      );
      coveredIssues.add(inconsistencies[inconsistencies.length - 1].issue);
    }
  }

  // 6. SLA breach check (urgency indicator only, strictly WARNING, never affects suggestedDecision)
  if (isSlaBreached(app.submittedAt, app.status, now)) {
    inconsistencies.push({
      fieldOrDoc: lang === "en" ? "Application Timeline (SLA)" : "आवेदन समय-सीमा (SLA)",
      issue:
        lang === "en"
          ? `This application has been pending for ${daysPending} days, exceeding the ${SLA_BREACH_DAYS}-day statutory Right to Service (SLA) limit.`
          : `यह आवेदन ${daysPending} दिनों से लंबित है, जो ${SLA_BREACH_DAYS} दिवसीय सेवा अधिकार (SLA) सीमा का उल्लंघन है।`,
      severity: "WARNING",
    });
  }

  // 7. Duplicate check (same normalized name + village + calendar birth date)
  const currentSubTime = new Date(app.submittedAt).getTime();

  if (options.existingApplications && app.id) {
    const priorDuplicate = options.existingApplications.find(
      (cand) =>
        cand.id !== app.id &&
        isDuplicateApplication(app, cand) &&
        currentSubTime > new Date(cand.submittedAt).getTime()
    );
    if (priorDuplicate) {
      inconsistencies.push({
        fieldOrDoc: lang === "en" ? "Applicant Identity / Previous Records" : "आवेदक पहचान / पूर्व रिकॉर्ड",
        issue:
          lang === "en"
            ? `Potential duplicate: An earlier application (ID: ${priorDuplicate.id}, Date: ${new Date(priorDuplicate.submittedAt).toLocaleDateString("en-US")}) is already registered with matching name, village, and date of birth.`
            : `संभावित डुप्लीकेट: समान नाम, गाँव व जन्म तिथि पर पूर्व आवेदन (ID: ${priorDuplicate.id}, दिनांक: ${new Date(priorDuplicate.submittedAt).toLocaleDateString("hi-IN")}) पहले से दर्ज है।`,
        severity: "CRITICAL",
      });
      reasons.push(
        lang === "en"
          ? `Prior application (ID: ${priorDuplicate.id}) already exists with matching applicant details. Physical verification required.`
          : `समान आवेदक विवरण पर पूर्व आवेदन (ID: ${priorDuplicate.id}) पहले से दर्ज है, भौतिक सत्यापन आवश्यक है।`
      );
      coveredIssues.add(inconsistencies[inconsistencies.length - 1].issue);
    }
  } else if (options.checkDbDuplicates && app.id) {
    try {
      const dobDate = new Date(app.dob);
      const startOfDay = new Date(dobDate.getFullYear(), dobDate.getMonth(), dobDate.getDate(), 0, 0, 0, 0);
      const endOfDay = new Date(dobDate.getFullYear(), dobDate.getMonth(), dobDate.getDate(), 23, 59, 59, 999);

      const candidates = await prisma.application.findMany({
        where: {
          id: { not: app.id },
          dob: {
            gte: startOfDay,
            lte: endOfDay,
          },
          submittedAt: {
            lt: app.submittedAt,
          },
        },
        select: { id: true, applicantName: true, village: true, dob: true, submittedAt: true },
      });

      const priorDuplicate = candidates.find((cand) =>
        isDuplicateApplication(app, cand)
      );

      if (priorDuplicate) {
        inconsistencies.push({
          fieldOrDoc: lang === "en" ? "Applicant Identity / Previous Records" : "आवेदक पहचान / पूर्व रिकॉर्ड",
          issue:
            lang === "en"
              ? `Potential duplicate: An earlier application (ID: ${priorDuplicate.id}, Date: ${new Date(priorDuplicate.submittedAt).toLocaleDateString("en-US")}) is already registered with matching name, village, and date of birth.`
              : `संभावित डुप्लीकेट: समान नाम, गाँव व जन्म तिथि पर पूर्व आवेदन (ID: ${priorDuplicate.id}, दिनांक: ${priorDuplicate.submittedAt.toLocaleDateString("hi-IN")}) पहले से दर्ज है।`,
          severity: "CRITICAL",
        });
        reasons.push(
          lang === "en"
            ? `Prior application (ID: ${priorDuplicate.id}) already exists with matching applicant details. Physical verification required.`
            : `समान आवेदक विवरण पर पूर्व आवेदन (ID: ${priorDuplicate.id}) पहले से दर्ज है, भौतिक सत्यापन आवश्यक है।`
        );
        coveredIssues.add(inconsistencies[inconsistencies.length - 1].issue);
      }
    } catch {
      // Offline fallback
    }
  }

  // 8. System flag note: strictly INFO
  if (app.flagNote) {
    const alreadyListed = inconsistencies.some((i) => i.issue === app.flagNote);
    if (!alreadyListed) {
      inconsistencies.push({
        fieldOrDoc: lang === "en" ? "System Flag Note" : "प्रणाली फ्लैग नोट",
        issue: app.flagNote,
        severity: "INFO",
      });
    }
  }

  // 9. Determine suggested decision
  let suggestedDecision: SuggestedDecision = "APPROVE";

  if (isUnderage || isOverIncome) {
    suggestedDecision = "REJECT";
  } else if (
    missingDocs.length > 0 ||
    inconsistencies.some((i) => i.severity === "CRITICAL")
  ) {
    suggestedDecision = "RETURN";
    if (missingDocs.length > 0) {
      const docNames =
        lang === "en"
          ? missingDocs.map((d) => DOC_NAME_EN[d] || d).join(", ")
          : missingDocs.join(", ");
      reasons.push(
        lang === "en"
          ? `Return application for submission of mandatory document(s): ${docNames}.`
          : `अनिवार्य दस्तावेज़ (${docNames}) संलग्न करने हेतु आवेदन वापस लौटाया जाए।`
      );
    }
  } else {
    suggestedDecision = "APPROVE";
    if (lang === "en") {
      reasons.push(
        `Applicant's age (${age} years) and annual income (₹${app.annualIncome.toLocaleString("en-IN")}) comply with statutory eligibility norms.`
      );
      reasons.push("All 6 mandatory documents are verified and attached.");
      if (normAppName === normBankHolder) {
        reasons.push(
          `Bank account holder name ('${app.bankAccountHolder}') verified and consistent with applicant.`
        );
      }
      const warnings = inconsistencies.filter(
        (i) => i.severity === "WARNING" && !coveredIssues.has(i.issue)
      );
      for (const w of warnings) {
        reasons.push(`Note (Warning): ${w.issue}`);
      }
    } else {
      reasons.push(
        `आवेदक की आयु (${age} वर्ष) एवं वार्षिक आय (₹${app.annualIncome.toLocaleString("hi-IN")}) पात्रता मानकों के अनुरूप हैं।`
      );
      reasons.push("सभी आवश्यक 6 अनिवार्य दस्तावेज़ संलग्न पाए गए।");
      if (normAppName === normBankHolder) {
        reasons.push(
          `बैंक खाता धारक नाम ('${app.bankAccountHolder}') आवेदक नाम के अनुरूप सत्यापित पाया गया।`
        );
      }
      const warnings = inconsistencies.filter(
        (i) => i.severity === "WARNING" && !coveredIssues.has(i.issue)
      );
      for (const w of warnings) {
        reasons.push(`ध्यान दें (चेतावनी): ${w.issue}`);
      }
    }
  }

  // REJECT/RETURN guarantee at least one reason
  if (suggestedDecision === "RETURN" || suggestedDecision === "REJECT") {
    for (const inc of inconsistencies) {
      if (inc.severity === "CRITICAL") {
        if (!reasons.includes(inc.issue) && !coveredIssues.has(inc.issue)) {
          reasons.push(inc.issue);
        }
      }
    }
    if (reasons.length === 0) {
      if (lang === "en") {
        reasons.push(
          suggestedDecision === "REJECT"
            ? "Application does not satisfy statutory old age pension eligibility criteria."
            : "Application contains missing documents or discrepancies; correction is required."
        );
      } else {
        reasons.push(
          suggestedDecision === "REJECT"
            ? "आवेदन वृद्धा पेंशन पात्रता शर्तों को पूरा नहीं करता है।"
            : "आवेदन में अनिवार्य दस्तावेज़ या विवरण अपूर्ण हैं, संशोधन अपेक्षित है।"
        );
      }
    }
  }

  // 10. Summary
  // Rule reasons first; CRITICAL issues restating the same fact are only a fallback.
  // Trailing sentence punctuation is stripped so joined reasons don't read "।;" or "।।".
  const criticalIssues = new Set(
    inconsistencies.filter((i) => i.severity === "CRITICAL").map((i) => i.issue)
  );
  const primaryReasons = reasons.filter((r) => !criticalIssues.has(r));
  const summaryReasons = (primaryReasons.length > 0 ? primaryReasons : reasons)
    .slice(0, 2)
    .map((r) => r.trim().replace(/[।.]+$/, ""))
    .join("; ");

  let summary = "";
  if (lang === "en") {
    summary = `Old age pension application for ${app.applicantName} (age ${age} years, resident of village ${app.village}, tehsil ${app.tehsil}). `;
    if (suggestedDecision === "APPROVE") {
      const warnings = inconsistencies.filter((i) => i.severity === "WARNING");
      if (warnings.length > 0) {
        summary += `Eligibility criteria and all 6 mandatory documents are fulfilled. Note: ${warnings.length} warning(s) identified (${warnings.map((w) => w.fieldOrDoc).join(", ")}); proceed with caution.`;
      } else {
        summary += `All statutory eligibility criteria are fulfilled and all 6 mandatory documents are attached. No discrepancies found.`;
      }
    } else if (suggestedDecision === "REJECT") {
      summary += `Application does not meet eligibility criteria. Primary reason: ${summaryReasons}.`;
    } else {
      summary += `Discrepancies or missing documents were found in the application. Return for necessary corrections and documentation is recommended.`;
    }
  } else {
    summary = `आवेदक ${app.applicantName} (आयु ${age} वर्ष, निवासी गाँव ${app.village}, तहसील ${app.tehsil}) का वृद्धा पेंशन आवेदन। `;
    if (suggestedDecision === "APPROVE") {
      const warnings = inconsistencies.filter((i) => i.severity === "WARNING");
      if (warnings.length > 0) {
        summary += `पात्रता शर्तें एवं 6 अनिवार्य दस्तावेज़ पूर्ण हैं। यद्यपि ${warnings.length} चेतावनी पाई गई है (${warnings.map((w) => w.fieldOrDoc).join(", ")}), जिसे संज्ञान में लेकर अग्रिम कार्यवाही करें।`;
      } else {
        summary += `सभी आवश्यक पात्रता शर्तें पूर्ण हैं एवं समस्त 6 अनिवार्य दस्तावेज़ संलग्न हैं। कोई विसंगति नहीं पाई गई।`;
      }
    } else if (suggestedDecision === "REJECT") {
      summary += `आवेदन पात्रता मानकों पर खरा नहीं उतरता है। मुख्य कारण: ${summaryReasons}।`;
    } else {
      summary += `आवेदन में कमियाँ/दस्तावेज़ी विसंगतियाँ पाई गई हैं। आवश्यक सुधार एवं दस्तावेज़ संलग्न करने हेतु आवेदन वापस लौटाया जाना अनुशंसित है।`;
    }
  }

  return {
    summary,
    missingDocuments: missingDocs,
    inconsistencies,
    suggestedDecision,
    reasons,
    confidence: "HIGH",
    source: "RULE_ENGINE",
    lang,
  };
}

// ─── LLM Provider (Groq or Gemini) ──────────────────────────────────────────

interface LlmProvider {
  label: string;
  /** Sends the prompt and returns the raw JSON text produced by the model */
  generateJson: (prompt: string) => Promise<string | undefined>;
}

const GROQ_DEFAULT_MODEL = "openai/gpt-oss-120b";
const GEMINI_DEFAULT_MODEL = "gemini-3.8-flash";
const LLM_TIMEOUT_MS = 25_000;

function isConfigured(key: string | undefined): key is string {
  return Boolean(key && !key.startsWith("YOUR_"));
}

/**
 * Picks the language-model provider from environment variables.
 * Groq (free tier, OpenAI-compatible) is preferred when its key is present;
 * Gemini is used otherwise; null means no key → rule engine only.
 */
export function getLlmProvider(): LlmProvider | null {
  const groqKey = process.env.GROQ_API_KEY;
  if (isConfigured(groqKey)) {
    const model = process.env.GROQ_MODEL || GROQ_DEFAULT_MODEL;
    return {
      label: `Groq · ${model}`,
      generateJson: async (prompt) => {
        const res = await fetch("https://api.groq.com/openai/v1/chat/completions", {
          method: "POST",
          headers: { Authorization: `Bearer ${groqKey}`, "Content-Type": "application/json" },
          body: JSON.stringify({
            model,
            messages: [{ role: "user", content: prompt }],
            response_format: { type: "json_object" },
            temperature: 0.2,
            // gpt-oss models think before answering; "low" keeps the free-tier token budget in check
            ...(model.startsWith("openai/gpt-oss") ? { reasoning_effort: "low" } : {}),
          }),
          signal: AbortSignal.timeout(LLM_TIMEOUT_MS),
        });
        if (!res.ok) {
          throw new Error(`Groq API ${res.status}: ${(await res.text()).slice(0, 300)}`);
        }
        const data = (await res.json()) as { choices?: { message?: { content?: string } }[] };
        return data.choices?.[0]?.message?.content?.trim();
      },
    };
  }

  const geminiKey = process.env.GEMINI_API_KEY;
  if (isConfigured(geminiKey)) {
    const model = process.env.AI_MODEL || GEMINI_DEFAULT_MODEL;
    return {
      label: `Google Gemini · ${model}`,
      generateJson: async (prompt) => {
        const ai = new GoogleGenAI({ apiKey: geminiKey });
        const response = await ai.models.generateContent({
          model,
          contents: prompt,
          config: { responseMimeType: "application/json" },
        });
        return response.text?.trim();
      },
    };
  }

  return null;
}

// ─── LLM + Rule Engine Merger ───────────────────────────────────────────────

export async function analyzeApplication(
  app: Application,
  options?: RuleEngineOptions
): Promise<AIAnalysisResult> {
  const lang = options?.lang || "hi";

  // 1. ALWAYS run the deterministic rule engine first
  const ruleResult = await analyzeWithRules(app, options);

  const provider = getLlmProvider();
  if (!provider) {
    return {
      ...ruleResult,
      source: "RULE_ENGINE",
      fallbackMessage:
        lang === "en"
          ? "AI service is unavailable (API key not configured). Local rule-based verification displayed."
          : "एआई सेवा उपलब्ध नहीं है (API कुंजी अनुपलब्ध)। स्थानीय नियम-आधारित सत्यापन प्रदर्शित है।",
      lang,
    };
  }

  try {
    const now = options?.now || new Date();
    const age = calculateAge(app.dob, now);
    const daysPending = calculateDaysPending(app.submittedAt, now);

    const prompt =
      lang === "en"
        ? `
You are an expert Old Age Pension Review AI for the Department of Social Welfare, Government of Haryana.
Please perform an objective, rigorous, and thorough review of the following pension application.
Provide the entire response in natural, professional administrative English for government reviewing officers, formatted strictly in the specified JSON schema.

Statutory Eligibility Criteria:
1. Minimum age: ${MIN_AGE_YEARS} years (Current applicant age: ${age} years)
2. Maximum annual household income: ₹${MAX_ANNUAL_INCOME_INR.toLocaleString("en-IN")} (Recorded income: ₹${app.annualIncome.toLocaleString("en-IN")})
3. Mandatory documents (all 6 required): ${REQUIRED_DOCUMENTS.map((d) => DOC_NAME_EN[d] || d).join(", ")}
4. Bank account holder name must match the applicant name exactly for DBT transfers.
5. SLA threshold: ${SLA_BREACH_DAYS} days (Current waiting period: ${daysPending} days)

Discrepancies already detected by deterministic rule engine:
${JSON.stringify(ruleResult.inconsistencies, null, 2)}
Missing documents detected by rule engine:
${JSON.stringify(ruleResult.missingDocuments.map((d) => DOC_NAME_EN[d] || d))}

Application Details:
- Applicant Name: ${app.applicantName}
- Father / Husband Name: ${app.fatherHusbandName}
- Date of Birth: ${new Date(app.dob).toISOString().split("T")[0]} (Age: ${age} years)
- Village, Tehsil, District: ${app.village}, ${app.tehsil}, ${app.district}
- Annual Income: ₹${app.annualIncome}
- Aadhaar No. (Masked): ${app.aadhaarMasked}
- Bank Account Holder: ${app.bankAccountHolder}
- Bank IFSC: ${app.bankIFSC}
- Bank Account No. (Masked): ${app.bankAccountMasked}
- Submitted Documents: ${JSON.stringify(app.documentsSubmitted)}
- Submission Date: ${new Date(app.submittedAt).toISOString().split("T")[0]} (${daysPending} days ago)
- Flag Note: ${app.flagNote || "None"}

Mandatory Instructions:
- For every discrepancy, cite the exact affected field or document name.
- If age < 60 or income > ₹2,00,000, the decision CAN NEVER be "APPROVE".
- A pending-time / SLA breach is the office's own delay, not a defect in the application: mention it as urgency, but NEVER use it as a reason to RETURN or REJECT.
- Respond ONLY with valid JSON:
{
  "summary": "2-3 sentence clear summary of applicant and eligibility status in professional English",
  "missingDocuments": ["Missing document name"],
  "inconsistencies": [
    {
      "fieldOrDoc": "Affected field or document name",
      "issue": "Specific discrepancy explanation in English",
      "severity": "CRITICAL" | "WARNING" | "INFO"
    }
  ],
  "suggestedDecision": "APPROVE" | "REJECT" | "RETURN",
  "reasons": ["Reason 1 in English", "Reason 2 in English"],
  "confidence": "HIGH" | "MEDIUM" | "LOW"
}
`
        : `
आप हरियाणा सरकार के समाज कल्याण विभाग में ब्लॉक/तहसील स्तर के वृद्धा पेंशन समीक्षा विशेषज्ञ AI हैं।
कृपया निम्नलिखित आवेदन की निष्पक्ष, गहन एवं सटीक समीक्षा करें।
सम्पूर्ण उत्तर केवल शुद्ध देवनागरी हिन्दी (Hindi) में और दिए गए JSON प्रारूप में ही दें।

पात्रता नियम:
1. न्यूनतम आयु: ${MIN_AGE_YEARS} वर्ष (वर्तमान आयु: ${age} वर्ष)
2. अधिकतम वार्षिक आय: ₹${MAX_ANNUAL_INCOME_INR.toLocaleString("en-IN")} (दर्ज आय: ₹${app.annualIncome.toLocaleString("en-IN")})
3. अनिवार्य दस्तावेज़: ${REQUIRED_DOCUMENTS.join(", ")}
4. बैंक खाता धारक का नाम आवेदक के नाम से अक्षरशः मेल खाना चाहिए।
5. SLA सीमा: ${SLA_BREACH_DAYS} दिन (वर्तमान प्रतीक्षा: ${daysPending} दिन)

नियम इंजन द्वारा पहले ही पहचानी गई विसंगतियाँ:
${JSON.stringify(ruleResult.inconsistencies, null, 2)}
नियम इंजन द्वारा पाए गए लापता दस्तावेज़:
${JSON.stringify(ruleResult.missingDocuments)}

आवेदन विवरण:
- आवेदक का नाम: ${app.applicantName}
- पिता/पति का नाम: ${app.fatherHusbandName}
- जन्म तिथि: ${new Date(app.dob).toISOString().split("T")[0]} (आयु: ${age} वर्ष)
- गाँव/तहसील/जिला: ${app.village}, ${app.tehsil}, ${app.district}
- वार्षिक आय: ₹${app.annualIncome}
- आधार सं. (मास्क्ड): ${app.aadhaarMasked}
- बैंक खाता धारक: ${app.bankAccountHolder}
- बैंक IFSC: ${app.bankIFSC}
- बैंक खाता सं. (मास्क्ड): ${app.bankAccountMasked}
- जमा किए गए दस्तावेज़: ${JSON.stringify(app.documentsSubmitted)}
- आवेदन तिथि: ${new Date(app.submittedAt).toISOString().split("T")[0]} (${daysPending} दिन पूर्व)
- फ्लैग नोट: ${app.flagNote || "कोई नहीं"}

महत्वपूर्ण निर्देश:
- प्रत्येक विसंगति के साथ संबंधित फ़ील्ड या दस्तावेज़ का स्पष्ट उल्लेख करें।
- यदि आयु 60 से कम है या आय ₹2,00,000 से अधिक है, तो निर्णय कदापि "APPROVE" नहीं हो सकता।
- लंबित अवधि / SLA उल्लंघन कार्यालय की अपनी देरी है, आवेदन की कमी नहीं: इसे तत्कालता के रूप में बताएँ, परंतु इसे RETURN या REJECT का कारण कदापि न बनाएँ।
- उत्तर केवल मान्य JSON में दें:
{
  "summary": "2-3 पंक्तियों में आवेदक व स्थिति का स्पष्ट सारांश",
  "missingDocuments": ["लापता दस्तावेज़"],
  "inconsistencies": [
    {
      "fieldOrDoc": "संबंधित फ़ील्ड/दस्तावेज़",
      "issue": "विसंगति का विवरण",
      "severity": "CRITICAL" | "WARNING" | "INFO"
    }
  ],
  "suggestedDecision": "APPROVE" | "REJECT" | "RETURN",
  "reasons": ["कारण 1", "कारण 2"],
  "confidence": "HIGH" | "MEDIUM" | "LOW"
}
`;

    const text = await provider.generateJson(prompt);
    if (!text) {
      return {
        ...ruleResult,
        source: "RULE_ENGINE",
        fallbackMessage:
          lang === "en"
            ? "No response received from AI service. Local rule-based verification displayed."
            : "एआई से कोई प्रत्युत्तर प्राप्त नहीं हुआ। स्थानीय नियम-आधारित सत्यापन प्रदर्शित है।",
        lang,
      };
    }

    // 2. Validate the model's JSON output with Zod at runtime
    const parsedJson = JSON.parse(text);
    const validated = geminiOutputSchema.safeParse(parsedJson);

    if (!validated.success) {
      console.warn(`${provider.label} output failed zod validation:`, validated.error);
      return {
        ...ruleResult,
        source: "RULE_ENGINE",
        fallbackMessage:
          lang === "en"
            ? "AI output failed schema validation. Local rule-based verification displayed."
            : "एआई प्रत्युत्तर सत्यापन में विफल रहा। स्थानीय नियम-आधारित सत्यापन प्रदर्शित है।",
        lang,
      };
    }

    const aiData = validated.data;

    // 3. MERGE & HARD RULE ENFORCEMENT:
    const isHardRuleFailed =
      calculateAge(app.dob, now) < MIN_AGE_YEARS ||
      app.annualIncome > MAX_ANNUAL_INCOME_INR;

    const hasMissingOrCritical =
      ruleResult.missingDocuments.length > 0 ||
      ruleResult.inconsistencies.some((i) => i.severity === "CRITICAL");

    let finalDecision: SuggestedDecision = aiData.suggestedDecision;
    let finalReasons: string[];
    let finalSummary = aiData.summary || ruleResult.summary;

    // Rule-engine reasons justify the rule engine's own decision; merging them into a
    // different AI decision would mix contradictory statements (e.g. "name verified" + "name mismatch").
    // When both agree, the AI's reasons restate the rule reasons in other words, so keep just
    // one set: the AI's (warnings are re-added below), or the rule reasons if the AI gave none.
    const reasonsFor = (decision: SuggestedDecision) =>
      decision === ruleResult.suggestedDecision && aiData.reasons.length === 0
        ? [...ruleResult.reasons]
        : [...aiData.reasons];

    if (isHardRuleFailed) {
      finalDecision = "REJECT";
      finalReasons = [...ruleResult.reasons];
      finalSummary = ruleResult.summary;
    } else if (finalDecision === "REJECT") {
      finalDecision = "RETURN";
      finalReasons = reasonsFor(finalDecision);
      if (finalReasons.length === 0) {
        finalReasons.push(
          lang === "en"
            ? "Application returned for rectification of identified discrepancies."
            : "आवेदन में पाई गई विसंगतियों के संशोधन हेतु वापस लौटाया जाना अनुशंसित है।"
        );
      }
    } else if (hasMissingOrCritical && finalDecision === "APPROVE") {
      finalDecision = "RETURN";
      finalReasons = [...ruleResult.reasons];
      finalSummary = ruleResult.summary;
    } else {
      finalReasons = reasonsFor(finalDecision);
    }

    // Merge inconsistencies (avoiding duplicates)
    const mergedInconsistencies = [...ruleResult.inconsistencies];
    for (const item of aiData.inconsistencies) {
      const exists = mergedInconsistencies.some(
        (existing) =>
          existing.fieldOrDoc.toLowerCase() === item.fieldOrDoc.toLowerCase()
      );
      if (!exists) {
        mergedInconsistencies.push({
          fieldOrDoc: item.fieldOrDoc,
          issue: item.issue,
          severity: item.severity as InconsistencySeverity,
        });
      }
    }

    // Never include false claim "आधार मिलान सफल रहा" in reasons
    finalReasons = finalReasons.filter((r) => !r.includes("आधार मिलान सफल रहा"));

    // If APPROVE, ensure any WARNINGs are mentioned
    if (finalDecision === "APPROVE") {
      const warnings = mergedInconsistencies.filter((i) => i.severity === "WARNING");
      for (const w of warnings) {
        const warningText =
          lang === "en" ? `Note (Warning): ${w.issue}` : `ध्यान दें (चेतावनी): ${w.issue}`;
        if (!finalReasons.includes(warningText)) {
          finalReasons.push(warningText);
        }
      }
    }

    // Ensure REJECT or RETURN always has at least one reason
    if (finalDecision === "REJECT" || finalDecision === "RETURN") {
      if (finalReasons.length === 0) {
        finalReasons.push(
          lang === "en"
            ? finalDecision === "REJECT"
              ? "Application does not satisfy statutory old age pension eligibility criteria."
              : "Application contains missing documents or discrepancies; correction is required."
            : finalDecision === "REJECT"
            ? "आवेदन पात्रता शर्तों को पूरा नहीं करता है।"
            : "आवेदन में अनिवार्य दस्तावेज़ या विवरण अपूर्ण हैं, संशोधन अपेक्षित है।"
        );
      }
    }

    return {
      summary: finalSummary,
      missingDocuments: Array.from(
        new Set([...ruleResult.missingDocuments, ...aiData.missingDocuments])
      ),
      inconsistencies: mergedInconsistencies,
      suggestedDecision: finalDecision,
      reasons: finalReasons,
      confidence: aiData.confidence,
      source: "LLM",
      model: provider.label,
      lang,
    };
  } catch (error) {
    console.error(`${provider.label} error, falling back to rule engine:`, error);
    return {
      ...ruleResult,
      source: "RULE_ENGINE",
      fallbackMessage:
        lang === "en"
          ? "AI service is temporarily unavailable. Local rule-based verification displayed."
          : "एआई सेवा अस्थायी रूप से अनुपलब्ध है। स्थानीय नियम-आधारित सत्यापन प्रदर्शित है।",
      lang,
    };
  }
}

// ─── Caching Layer in Database ──────────────────────────────────────────────

/**
 * Reads cached AI analysis from Application.aiAnalysis.
 * Computes and writes to DB only when the language model succeeds.
 * Supports language caching: if cached language matches requested language, returns cache.
 */
export async function getOrComputeAnalysis(
  applicationId: string,
  forceRefresh = false,
  lang: "hi" | "en" = "hi"
): Promise<AIAnalysisResult> {
  const app = await prisma.application.findUnique({
    where: { id: applicationId },
  });

  if (!app) {
    throw new Error("Application not found");
  }

  // Return cached result if available and not forcing a refresh, UNLESS
  // the cached result was an AI failure fallback (RULE_ENGINE) and a valid key is now present,
  // or if the cached language doesn't match the currently requested language.
  if (app.aiAnalysis && !forceRefresh) {
    const cached = app.aiAnalysis as unknown as AIAnalysisResult;
    const cachedLang = cached.lang || "hi";
    if (cached.source === "RULE_ENGINE" && getLlmProvider()) {
      // A provider is configured now: replace the old fallback with a real AI analysis
    } else if (cachedLang === lang) {
      return cached;
    }
  }

  // Compute fresh analysis in requested language
  const freshAnalysis = await analyzeApplication(app, { lang });

  // Cache in database ONLY if successfully generated by the language model
  if (freshAnalysis.source !== "RULE_ENGINE") {
    try {
      await prisma.application.update({
        where: { id: applicationId },
        data: {
          aiAnalysis: { ...freshAnalysis, lang } as never,
          analyzedAt: new Date(),
        },
      });
    } catch (err) {
      console.error("Failed to cache AI analysis in database:", err);
    }
  }

  return freshAnalysis;
}
